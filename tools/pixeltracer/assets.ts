#!/usr/bin/env node

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Scene } from './src/scene.ts'
import { CACHE_OUT } from './src/palette.ts'
import { defaultRenderOpts, renderRaw, pixelize } from './src/render.ts'
import { encodePng } from './src/png.ts'
import { chip, DENOMINATIONS } from './scenes/cacheout/chip.ts'
import type { Denomination } from './scenes/cacheout/chip.ts'
import { die } from './scenes/cacheout/die.ts'
import { bar, cherry, seven, trophy } from './scenes/cacheout/symbols.ts'
import { dealer, MOOD_NAMES } from './scenes/cacheout/dealer.ts'
import { v3 } from './src/vec3.ts'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..')
const SPRITES = join(ROOT, 'src', 'assets', 'sprites')
const STYLES = join(ROOT, 'src', 'styles')

export type AssetSpec = {
  name: string

  size: number
  upscale: number

  frames: (aspect: number) => Scene[]
}

function renderSheet(spec: AssetSpec): {
  data: Uint8Array
  width: number
  height: number
  frames: number
} {
  const scenes = spec.frames(1)
  const opts = {
    ...defaultRenderOpts(CACHE_OUT),
    width: spec.size,
    height: spec.size,
    upscale: spec.upscale,
    transparentBackground: true,
  }

  const tiles = scenes.map((scene) => pixelize(renderRaw(scene, opts), opts))
  const tileW = tiles[0].width
  const tileH = tiles[0].height
  const sheetW = tileW * tiles.length
  const data = new Uint8Array(sheetW * tileH * 4)

  tiles.forEach((tile, i) => {
    for (let y = 0; y < tileH; y++) {
      for (let x = 0; x < tileW; x++) {
        const src = (y * tileW + x) * 4
        const dst = (y * sheetW + i * tileW + x) * 4
        data.set(tile.data.subarray(src, src + 4), dst)
      }
    }
  })

  return { data, width: sheetW, height: tileH, frames: tiles.length }
}

const SPIN_FRAMES = 16
const ROLL_FRAMES = 12

const ASSETS: AssetSpec[] = [
  ...(Object.keys(DENOMINATIONS) as Denomination[]).map((d) => ({
    name: `chip-${d}`,
    size: 40,
    upscale: 4,
    frames: (a: number) => [chip(d, 0, a)],
  })),
  {
    name: 'chip-spin',
    size: 40,
    upscale: 4,

    frames: (a: number) =>
      Array.from({ length: SPIN_FRAMES }, (_, i) =>
        chip('red', (i / SPIN_FRAMES) * Math.PI * 2, a),
      ),
  },
  { name: 'die', size: 44, upscale: 4, frames: (a: number) => [die(undefined, a)] },
  {
    name: 'die-roll',
    size: 44,
    upscale: 4,

    frames: (a: number) =>
      Array.from({ length: ROLL_FRAMES }, (_, i) => {
        const t = (i / ROLL_FRAMES) * Math.PI * 2
        return die(v3(0.42 + Math.sin(t) * 0.9, t, Math.cos(t) * 0.35), a)
      }),
  },
  { name: 'slot-seven', size: 44, upscale: 4, frames: (a: number) => [seven(a)] },
  { name: 'slot-cherry', size: 44, upscale: 4, frames: (a: number) => [cherry(a)] },
  { name: 'slot-bar', size: 44, upscale: 4, frames: (a: number) => [bar(a)] },
  { name: 'trophy', size: 48, upscale: 4, frames: (a: number) => [trophy(a)] },
  ...MOOD_NAMES.map((m) => ({
    name: `dealer-${m}`,
    size: 56,
    upscale: 4,
    frames: (a: number) => [dealer(m, a)],
  })),
]

function emitPaletteCss(): string {
  const lines = CACHE_OUT.entries.map((e) => `  --co-${e.name}: ${e.hex};`)
  return `/* Generated by npm run assets. */
:root {
${lines.join('\n')}
}
`
}

function main(): void {
  mkdirSync(SPRITES, { recursive: true })
  mkdirSync(STYLES, { recursive: true })

  const manifest: Record<string, { file: string; frames: number; width: number; height: number }> =
    {}
  const t0 = Date.now()

  for (const spec of ASSETS) {
    const sheet = renderSheet(spec)
    const file = `${spec.name}.png`
    writeFileSync(join(SPRITES, file), encodePng(sheet.data, sheet.width, sheet.height))
    manifest[spec.name] = {
      file,
      frames: sheet.frames,
      width: sheet.width / sheet.frames,
      height: sheet.height,
    }
    console.log(
      `  ${spec.name.padEnd(14)} ${String(sheet.frames).padStart(2)} frame(s)  ${sheet.width}x${sheet.height}`,
    )
  }

  writeFileSync(join(SPRITES, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  writeFileSync(join(STYLES, 'palette.css'), emitPaletteCss())

  console.log(`\n${ASSETS.length} assets + palette.css in ${Date.now() - t0}ms`)
}

main()
